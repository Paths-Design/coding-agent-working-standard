#!/usr/bin/env node
// CAWS-DESIGN-GLOBAL-IDENTITY-HOME-001 A2: generate
// src/init/hook-packs/surfaces.generated.ts from surfaces/registry.json.
// Deterministic: same input -> byte-identical output.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const registry = JSON.parse(
  readFileSync(join(here, '..', 'surfaces', 'registry.json'), 'utf8')
);
const entries = Object.entries(registry.surfaces);

const union = entries.map(([id]) => `'${id}'`).join(' | ');
const list = entries.map(([id]) => `'${id}'`).join(', ');
const envVars = entries
  .map(([id, s]) => `  '${id}': [${(s.envVars ?? []).map((v) => `'${v}'`).join(', ')}],`)
  .join('\n');
const pinVars = entries
  .filter(([, s]) => s.pinVar !== null && s.pinVar !== undefined)
  .map(([id, s]) => `  '${id}': '${s.pinVar}',`)
  .join('\n');
const gated = entries.filter(([, s]) => s.trustGated === true).map(([id]) => `'${id}'`);
const mechanisms = entries
  .map(([id, s]) => `  '${id}': '${s.hookMechanism}',`)
  .join('\n');
const sentinel = entries.find(([, s]) => s.sentinel === true)?.[0] ?? 'none';

const out = `// @generated — DO NOT EDIT.
// Source: packages/caws-cli/surfaces/registry.json (version ${registry.version}).
// Regenerated by scripts/generate-surface-registry.mjs; the build fails when
// this file drifts from the registry (check-surface-registry.mjs).
// CAWS-DESIGN-GLOBAL-IDENTITY-HOME-001 A2: one registry edit adds a surface.

export type AgentSurface = ${union};

export const AGENT_SURFACES: readonly AgentSurface[] = [${list}];

/** Per-surface session-identity env vars, in precedence order. */
export const SURFACE_ENV_VARS: Readonly<Record<AgentSurface, readonly string[]>> = {
${envVars}
};

/** The env var the surface pin prefers when CAWS_AGENT_SURFACE names the
 *  platform. Absent for surfaces with no per-session env var. */
export const SURFACE_PIN_VARS: Readonly<Partial<Record<AgentSurface, string>>> = {
${pinVars}
};

/** Trust-gated surfaces: project-scope wiring can be silently disabled by the
 *  harness (see the registry's trustGated field). */
export const TRUST_GATED_SURFACES: readonly AgentSurface[] = [${gated.join(', ')}];

/** The hook mechanism each harness exposes (shell-hooks, js-plugin, ...). */
export const SURFACE_HOOK_MECHANISMS: Readonly<Record<AgentSurface, string>> = {
${mechanisms}
};

/** The sentinel surface ('none'): generic identity, no harness. */
export const SENTINEL_SURFACE: AgentSurface = '${sentinel}';
`;

writeFileSync(join(here, '..', 'src', 'init', 'hook-packs', 'surfaces.generated.ts'), out);
console.log('surface registry generated: src/init/hook-packs/surfaces.generated.ts');
