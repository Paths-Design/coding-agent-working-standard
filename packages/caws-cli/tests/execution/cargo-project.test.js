const hash = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
function fixture(name = 'example-probe', version = '2.3.4', edition = '2021') {
  const root = fs.realpathSync.native(
    fs.mkdtempSync(path.join(os.tmpdir(), 'caws-cargo-project-'))
  );
  roots.push(root);
  const cwd = path.join(root, 'project');
  const pkg = path.join(cwd, 'rust-probe');
  fs.mkdirSync(path.join(pkg, 'src'), { recursive: true });
  const manifest = path.join(pkg, 'Cargo.toml');
  const lock = path.join(pkg, 'Cargo.lock');
  const entry = path.join(pkg, 'src/main.rs');
  fs.writeFileSync(
    manifest,
    `[package]\nname = "${name}"\nversion = "${version}"\nedition = "${edition}"\n`
  );
  fs.writeFileSync(
    lock,
    `# Generated by Cargo\nversion = 4\n\n[[package]]\nname = "${name}"\nversion = "${version}"\n`
  );
  fs.writeFileSync(entry, 'fn main() { println!("example"); }\n');
  return {
    root,
    cwd,
    pkg,
    manifest,
    lock,
    entry,
    snapshot: () => snapshotCargoProject(cwd, 'rust-probe/Cargo.toml', Date.now() + 30000),
  };
}
function reason(action) {
  try {
    action();
  } catch (error) {
    return error.reason;
  }
  throw new Error('Expected snapshot refusal');
}

test.each(['2015', '2018', '2021', '2024'])(
  'captures independent package identity and edition %s without executing code',
  (edition) => {
    const f = fixture('Other_package-7', '12.0.9', edition);
    const before = [f.manifest, f.lock, f.entry].map(hash);
    const first = f.snapshot();
    expect(first).toEqual({
      manifest: { path: f.manifest, sha256: before[0] },
      lock: { path: f.lock, sha256: before[1] },
      entry: { path: f.entry, sha256: before[2] },
      packageName: 'Other_package-7',
      version: '12.0.9',
      edition,
      configurationSha256: first.configurationSha256,
    });
    expect(first.configurationSha256).toMatch(/^[0-9a-f]{64}$/);
    expect(first).toEqual(f.snapshot());
    expect(Object.isFrozen(first)).toBe(true);
    expect([f.manifest, f.lock, f.entry].map(hash)).toEqual(before);
    expect(fs.readdirSync(f.pkg).sort()).toEqual(['Cargo.lock', 'Cargo.toml', 'src']);
  }
);

test('accepts comments, CRLF, key reordering and lock v3 in the declared grammar', () => {
  const f = fixture();
  fs.writeFileSync(
    f.manifest,
    '# comment\r\n[package] # package\r\nedition="2021"\r\nversion="2.3.4" # version\r\nname="example-probe"\r\n'
  );
  fs.writeFileSync(f.lock, 'version=3\n[[package]]\nversion="2.3.4"\nname="example-probe"\n');
  expect(f.snapshot().packageName).toBe('example-probe');
  expect(f.snapshot().lock.sha256).toBe(hash(f.lock));
});

