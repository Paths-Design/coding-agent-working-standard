function duringRead(f, target, mutate) {
  const inode = fs.statSync(target).ino;
  const read = fs.readSync;
  let changed = false;
  jest.spyOn(fs, 'readSync').mockImplementation((fd, ...args) => {
    const count = read(fd, ...args);
    if (!changed && count > 0 && fs.fstatSync(fd).ino === inode) {
      changed = true;
      mutate();
    }
    return count;
  });
  expect(reason(f.snapshot)).toBe('unsupported_profile');
  expect(changed).toBe(true);
}

