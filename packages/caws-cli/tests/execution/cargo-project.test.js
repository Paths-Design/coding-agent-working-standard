test('configuration digest observes input identity and existing empty configuration directory', () => {
  const f = fixture();
  const original = f.snapshot();
  fs.renameSync(f.entry, f.entry + '.old');
  fs.copyFileSync(f.entry + '.old', f.entry);
  const replaced = f.snapshot();
  expect(replaced.entry).toEqual(original.entry);
  expect(replaced.configurationSha256).not.toBe(original.configurationSha256);
  fs.mkdirSync(path.join(f.pkg, '.cargo'));
  const directory = f.snapshot();
  expect(directory.configurationSha256).not.toBe(replaced.configurationSha256);
});

